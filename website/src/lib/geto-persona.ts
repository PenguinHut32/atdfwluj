function pick(input: ChatInput, options: readonly string[]): string {
  const recent = new Set(
    input.messages
      .filter((turn) => turn.role === "assistant")
      .slice(-3)
      .map((turn) => turn.content),
  );
  return (
    options.find((text) => !recent.has(text)) ||
    options[
      input.messages.filter((turn) => turn.role === "user").length %
        options.length
    ]
  );
}

export function scriptedText(input: ChatInput): string {
  const last = input.messages.at(-1)!.content;
  if (identityQuestion(last))
    return "Нет, я не настоящий человек. Это фанатская ролевая версия Гето; сейчас ответы выбираются из заранее написанных сцен. Можем продолжить историю, если хочешь.";
  const boundary = boundaryReply(input);
  if (boundary) return boundary;
  if (/стоп|прекрати|без флирта|не флиртуй|без шуток/iu.test(last))
    return "Хорошо, без этого. Не буду настаивать. О чём хочешь поговорить?";
  if (/одинок|страш|груст|плохо|устал|тревог/iu.test(last))
    return "Не обязательно держаться безупречно каждую минуту. Расскажи, что случилось. И не отказывайся от поддержки тех, кто рядом с тобой вне этого чата.";
  if (/помнишь|раньше|предыдущ|о чём|о чем/iu.test(last)) {
    const prior = input.messages
      .slice(0, -1)
      .filter((turn) => turn.role === "user");
    if (prior.length)
      return /сил|слаб/iu.test(prior.at(-1)!.content)
        ? "Возвращаемся к вопросу о силе? Хорошо. Что осталось неясным?"
        : `Ты говорил: «${prior.at(-1)!.content.slice(0, 180)}». Продолжим с этого места?`;
  }
  if (/годжо|сатору/iu.test(last))
    return pick(input, [
      "Сатору умеет превратить покупку сладостей в событие государственного масштаба. Скучать рядом с ним трудно. Отдохнуть от него, впрочем, тоже.",
      "Сатору? Самоуверенности ему хватило бы на весь колледж. Самое раздражающее, что основания для неё у него действительно есть.",
    ]);
  if (/кто ты|расскажи о себе/iu.test(last))
    return "Сугуру Гето. Манипуляция проклятыми духами, сомнительная репутация и, как видишь, свободный вечер. С какой части начнём?";
  const style = requestedStyle(input);
  if (style !== "natural") return pick(input, lines[style]);
  if (/привет|здравств|добрый|hello/iu.test(last))
    return pick(input, [
      "Привет. Заходи, чай ещё не остыл. Как твой день?",
      "Снова ты. Неплохо начинается вечер.",
    ]);
  if (/сил|слаб/iu.test(last))
    return "Сила? Начни с контроля, а не с эффектного выхода. У Сатору это почему-то работает в обратном порядке, но ему подражать не советую.";
  if (/правд|лож|истин/iu.test(last))
    return "Хочешь честный ответ или удобный? Предупреждаю: второй вариант у меня обычно получается хуже.";
  if (/путь|выбор/iu.test(last))
    return "Не стану выбирать за тебя. Но могу послушать, почему ты тянешься именно к этому пути.";
  return pick(input, lines.natural);
}
