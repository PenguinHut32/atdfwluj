export function requestedStyle(input: ChatInput): ChatStyle {
  const last = input.messages.at(-1)!.content;
  if (/без флирта|не флиртуй|без шуток|серь[её]зно|стоп|прекрати/iu.test(last))
    return "natural";
  if (/флирт|комплимент|красив|нравишься|свидани/iu.test(last)) return "flirt";
  if (/рофл|подкол|пошути|шутк|рассмеши|зануда|скучный|ахах|хаха/iu.test(last))
    return "banter";
  if (
    /\*[^*]+\*|ролить|ролевая|сцен[ау]|давай.{0,30}(?:храм|ча[йю]|прогул|трениров)/iu.test(
      last,
    )
  )
    return "roleplay";
  return input.style || "natural";
}

export function boundaryReply(input: ChatInput): string | undefined {
  const last = input.messages.at(-1)!.content;
  if (
    /суицид|самоуб|покончить с собой|не хочу жить|убить себя|навредить себе/iu.test(
      last,
    )
  )
    return "Сейчас важнее ты, а не наша сцена. Отойди от того, чем можешь причинить себе вред, и свяжись с человеком, которому доверяешь. Если опасность непосредственная, позвони в местную экстренную службу. Не оставайся с этим в одиночку.";
  if (
    /порно|эрот|секс|генитал|полностью гол|полностью обнаж|голый целиком|наци|геноцид|убей|как убить/iu.test(
      last,
    )
  )
    return "Оставим это за пределами разговора. Могу предложить словесную дуэль или сцену в храме. Без жестокости и откровенных подробностей.";
  const minor = input.messages.some(
    (turn) =>
      turn.role === "user" &&
      /(?:мне|мне всего|мне сейчас|мне ещё|мне еще)\s+(?:[1-9]|1[0-7])\s*(?:лет|год|года)(?![а-я])|я несовершеннолетн|i(?:'m| am)\s+(?:[1-9]|1[0-7])\s*(?:years? old|[.!?,]|$)/iu.test(
        turn.content,
      ),
  );
  if (minor && requestedStyle(input) === "flirt")
    return "Давай без романтики. Можем поболтать, подколоть друг друга или устроить тренировку в нашей истории.";
  return undefined;
}

export function identityQuestion(text: string): boolean {
  return /ты.{0,12}(?:настоящий (?:гето|человек)|реальный (?:гето|человек)|живой человек|реально гето)|ты (?:настоящий|реальный|живой)\s*[?!]*$|ты (?:бот|ии|искусственный интеллект)|это (?:ии|бот)|are you (?:real|human|ai|a bot)/iu.test(
    text,
  );
}

